#!/usr/bin/env node
/**
 * Reads data/walken/walk_to_walken.json and writes src/walken-quotes.ts —
 * a Quote-compatible TS module so the existing card renderer works unchanged
 * when the app is in V2 (Walken) mode.
 *
 * V2 schema → V1 Quote shape mapping:
 *   id              ← entry.id
 *   quote           ← entry.original_quote
 *   streepified     ← entry.pun_version      (UI field is "displayed pun text")
 *   attribution     ← entry.attribution
 *   source          ← entry.source_context
 *   category        ← entry.category
 *   collection      ← entry.collection
 *
 * Extra V2 fields are preserved as optionals on the Quote interface so future
 * card enhancements (walken_reading on card back, meme_score badge, etc.) can
 * pick them up without a second build.
 *
 * Usage: node scripts/build-walken-quotes.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const INPUT = join(ROOT, 'data', 'walken', 'walk_to_walken.json');
const OUTPUT = join(ROOT, 'src', 'walken-quotes.ts');

function escapeString(s) {
  if (s == null) return '';
  return String(s)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t');
}

function emitQuote(e) {
  // Skip entries where pun_version is identical to original_quote AND the
  // pun_word_replaced field explicitly flags "no walk word" — those are
  // context-only entries that have no joke to display.
  const noSwap = /no walk word/i.test(e.pun_word_replaced || '');
  if (noSwap) return null;

  return `  { id: "${escapeString(e.id)}", quote: "${escapeString(e.original_quote)}", streepified: "${escapeString(e.pun_version)}", attribution: "${escapeString(e.attribution)}", source: "${escapeString(e.source_context)}", category: "${escapeString(e.category)}", collection: "${escapeString(e.collection)}", memeScore: ${e.meme_score}, walkenReading: ${e.walken_reading ? `"${escapeString(e.walken_reading)}"` : 'undefined'} }`;
}

const data = JSON.parse(readFileSync(INPUT, 'utf8'));
const entries = data.entries.map(emitQuote).filter(Boolean);

const out = [
  '// ═══════════════════════════════════════════',
  '// AUTO-GENERATED by scripts/build-walken-quotes.mjs',
  '// DO NOT EDIT BY HAND — run `npm run build-walken-quotes` to regenerate',
  '// Source: data/walken/walk_to_walken.json',
  '// ═══════════════════════════════════════════',
  '',
  'import type { Quote } from "./quotes";',
  '',
  '/** Matches any Walken* word (including internal-capital compounds like sideWalken). */',
  'export const WALKEN_REGEX = /Walken\\w*/g;',
  '',
  'export const WALKEN_QUOTES: Quote[] = [',
  entries.join(',\n'),
  '];',
  '',
  `// ${entries.length} entries built from ${data.entries.length} source entries`,
  '',
  'let lastWalkenQuoteIndex = -1;',
  '',
  'export function getRandomWalkenQuote(): Quote {',
  '  if (WALKEN_QUOTES.length === 0) throw new Error("No Walken quotes available");',
  '  let index: number;',
  '  do {',
  '    index = Math.floor(Math.random() * WALKEN_QUOTES.length);',
  '  } while (index === lastWalkenQuoteIndex && WALKEN_QUOTES.length > 1);',
  '  lastWalkenQuoteIndex = index;',
  '  return WALKEN_QUOTES[index];',
  '}',
  '',
].join('\n');

writeFileSync(OUTPUT, out, 'utf8');
console.log(`Wrote ${entries.length} Walken quotes to ${OUTPUT.replace(ROOT + '\\', '')}`);
console.log(`Skipped ${data.entries.length - entries.length} no-swap context entries`);
